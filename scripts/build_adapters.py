#!/usr/bin/env python3
"""Generate the manifests and thin agent wrappers that let ERM run in other agent harnesses.

The canonical sources are skills/, agents/ and resources/. Everything this script writes is derived
from them; edit the sources and re-run instead of editing the generated files.

    python3 scripts/build_adapters.py          # write generated files
    python3 scripts/build_adapters.py --check  # exit 1 if any generated file is out of date
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLAUDE = json.loads((ROOT / ".claude-plugin/plugin.json").read_text())
VERSION = CLAUDE["version"]
REPO = CLAUDE["repository"]
NAME = "erm"
DISPLAY = "Elephant-Referee Model"
SHORT = "Write research with an elephant. Referee it with a goldfish."
LONG = (
    "Take scientific work from research question to submission-ready manuscript. A context-rich agent "
    "(the elephant) brainstorms, drafts protocols and manuscripts with you; fresh reviewers with no memory "
    "of the conversation (goldfish) referee the document cold, checking scope, comprehension, methods, "
    "evaluation, claims, reproducibility, citations and figures. You decide on every finding. "
    "Reviews require isolated sub-agents."
)
AUTHOR = CLAUDE["author"]

HEADER_MD = "<!-- Generated by scripts/build_adapters.py from agents/{src}. Do not edit. -->\n"


def frontmatter(path: Path) -> dict:
    m = re.match(r"^---\n(.*?)\n---\n", path.read_text(encoding="utf-8"), re.S)
    out = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            out[k.strip()] = v.strip().strip('"')
    return out


# Goldfish allowed to use the web (bibliographic lookups only). Canonical persona files carry no
# tool list, because Claude Code and Gemini CLI read the same agents/ folder with incompatible schemas.
WEB_PERSONAS = {"erm-citation-auditor", "erm-lens"}

PERSONAS = []
for p in sorted((ROOT / "agents").glob("*.md")):
    fm = frontmatter(p)
    PERSONAS.append({"name": fm["name"], "description": fm["description"], "file": p.name,
                     "web": fm["name"] in WEB_PERSONAS})

files: dict[str, str] = {}


def as_json(obj) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


# --- Agent Plugins 1.0 (GitHub Copilot CLI, Antigravity) -------------------------------------
base_manifest = {
    "name": NAME,
    "displayName": DISPLAY,
    "version": VERSION,
    "description": SHORT,
    "author": AUTHOR,
    "homepage": REPO,
    "repository": REPO,
    "license": "Apache-2.0",
    "logo": "docs/assets/icon.svg",
}
files["plugin.json"] = as_json(base_manifest)
files[".plugin/plugin.json"] = as_json(
    {"$schema": "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json",
     **{k: v for k, v in base_manifest.items() if k not in ("displayName", "logo")}})

# --- Codex (CLI and desktop) -------------------------------------------------------------------
files[".codex-plugin/plugin.json"] = as_json({
    "name": NAME,
    "version": VERSION,
    "description": SHORT,
    "author": AUTHOR,
    "homepage": REPO,
    "repository": REPO,
    "license": "Apache-2.0",
    "skills": "./skills/",
    "requires_local_executor": True,
    "interface": {
        "displayName": DISPLAY,
        "shortDescription": "Draft research with context, referee it cold",
        "longDescription": LONG,
        "developerName": AUTHOR["name"],
        "brandColor": "#F08C2E",
        "category": "Productivity",
        "capabilities": ["Shape a research question", "Draft protocols and manuscripts",
                         "Referee a manuscript with fresh reviewers"],
        "defaultPrompt": [
            "Help me turn this research idea into a focused question and hypotheses.",
            "Referee this manuscript before I submit it.",
            "Check that my manuscript still matches my results.",
        ],
        "websiteURL": REPO,
        "supportURL": REPO + "/issues",
        "termsOfServiceURL": REPO + "/blob/main/LICENSE",
        "composerIcon": "./docs/assets/icon.svg",
        "logo": "./docs/assets/icon.svg",
    },
})
files[".agents/plugins/marketplace.json"] = as_json({
    "name": NAME,
    "interface": {"displayName": DISPLAY},
    "plugins": [{"name": NAME, "source": "./",
                 "policy": {"installation": "AVAILABLE", "authentication": "ON_INSTALL"},
                 "category": "Productivity"}],
})

# --- Gemini CLI extension ----------------------------------------------------------------------
files["gemini-extension.json"] = as_json({"name": NAME, "version": VERSION, "contextFileName": "GEMINI.md"})
files["GEMINI.md"] = (
    "<!-- Generated by scripts/build_adapters.py. Do not edit. -->\n"
    "# Elephant-Referee Model (ERM)\n\n"
    "This extension provides the ERM skills in `skills/` (erm-brainstorm, erm-protocol, erm-notebook, erm-draft, "
    "erm-review, erm-resolve, erm-drift, erm-provenance).\n\n"
    "Apply the following only when an ERM skill is running:\n\n"
    "- ERM_ROOT is this extension's directory. Resolve `agents/`, `resources/` and `docs/` against it.\n"
    "- Start every goldfish reviewer as a **new** sub-agent with the generic prompt in "
    "`resources/standards/dispatch-standard.md`. Pass absolute paths only. Never pass the conversation, "
    "a summary of it, or the author's intent.\n"
    "- If you cannot start an isolated sub-agent, stop the review and say so. Never review in your own "
    "context and call it a goldfish review.\n"
)

# --- Cursor --------------------------------------------------------------------------------------
files[".cursor-plugin/plugin.json"] = as_json({
    "name": NAME, "version": VERSION, "description": SHORT, "author": AUTHOR,
    "homepage": REPO, "repository": REPO, "license": "Apache-2.0",
    "logo": "docs/assets/icon.svg",
    "skills": "./skills/", "agents": "./.cursor-plugin/agents/", "rules": "./.cursor-plugin/rules/",
})
files[".cursor-plugin/rules/erm.mdc"] = (
    "---\ndescription: Runtime routing for ERM workflows only.\nalwaysApply: true\n---\n\n"
    "Apply these instructions only while an ERM skill (erm-*) is running.\n"
    "ERM_ROOT is the folder that contains `skills/`, `agents/` and `resources/`: two levels above the invoked "
    "`skills/<name>/SKILL.md`. Confirm `ERM_ROOT/.cursor-plugin/plugin.json` exists; "
    "otherwise ask the user for the installed package path.\n"
    "Follow `ERM_ROOT/resources/standards/dispatch-standard.md`. Use Task dispatch to the registered ERM "
    "reviewer types, one new task per reviewer and per run. Supply ERM_ROOT and absolute paths only; "
    "never the parent's history or reasoning. Reviewers are read-only: write each returned report verbatim "
    "to its output path.\n"
)
for p in PERSONAS:
    files[f".cursor-plugin/agents/{p['name']}.md"] = (
        f"---\nname: {p['name']}\ndescription: {json.dumps(p['description'], ensure_ascii=False)}\nmodel: inherit\nreadonly: true\n"
        "is_background: false\n---\n\n"
        f"Require an absolute ERM_ROOT in the task. Read ERM_ROOT/agents/{p['file']} first and follow that "
        "persona; ignore its frontmatter. Resolve resources/ against ERM_ROOT.\n"
        "Use only the files named in the task. Do not edit files or delegate. "
        "Return the full report to the parent; the parent writes it.\n"
        "If a required path cannot be read, return an incomplete review, never a passing verdict.\n"
    )

# --- GitHub Copilot CLI --------------------------------------------------------------------------
for p in PERSONAS:
    tools = "[read, search, web]" if p["web"] else "[read, search]"
    files[f"com.github.copilot/agents/{p['name']}.agent.md"] = (
        f"---\nname: {p['name']}\ndescription: {json.dumps(p['description'], ensure_ascii=False)}\ntools: {tools}\n"
        "include-custom-instructions: false\nuser-invocable: false\n---\n\n"
        f"Require an absolute ERM_ROOT in the task. Read ERM_ROOT/agents/{p['file']} first and follow that "
        "persona; ignore its frontmatter. Resolve resources/ against ERM_ROOT.\n"
        "Use only the files named in the task. Do not edit files or delegate. "
        "Return the full report to the parent; the parent writes it.\n"
        "If a required path cannot be read, return an incomplete review, never a passing verdict.\n"
    )


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for rel, content in files.items():
        path = ROOT / rel
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        if check:
            stale.append(rel)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print("wrote", rel)
    # Remove wrappers of personas that no longer exist.
    for folder, suffix in [(".cursor-plugin/agents", ".md"), ("com.github.copilot/agents", ".agent.md")]:
        for f in (ROOT / folder).glob("*" + suffix) if (ROOT / folder).exists() else []:
            rel = f"{folder}/{f.name}"
            if rel not in files:
                if check:
                    stale.append(rel)
                else:
                    f.unlink()
                    print("removed", rel)
    if check and stale:
        print("Out of date (run scripts/build_adapters.py):\n  " + "\n  ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
